// Получаем ID книги из адресной строки
const params = new URLSearchParams(window.location.search);
const bookId = params.get("id");

// Находим книгу
const book = Object.hasOwn(books, bookId) ? books[bookId] : null;

const bookDetails = document.getElementById("bookDetails");
const bookNotFound = document.getElementById("bookNotFound");

if (book) {
    document.title = book.title + " — BookSpace";

    document.getElementById("bookImage").src = book.image;
    document.getElementById("bookImage").alt = book.title;

    document.getElementById("bookTitle").textContent = book.title;
    document.getElementById("bookAuthor").textContent = book.author;
    document.getElementById("bookGenre").textContent = book.genre;
    document.getElementById("bookDescription").textContent =
        book.description;

    bookDetails.classList.remove("d-none");

    const statusSelect = document.getElementById("bookStatus");
    const addButton = document.getElementById("addToLibraryBtn");
    const message = document.getElementById("bookMessage");

    const storageKey = "bookspaceLibrary";

    // Проверяем, есть ли книга в библиотеке
    function loadLibrary() {
        try {
            const saved = JSON.parse(localStorage.getItem(storageKey));
            return Array.isArray(saved) ? saved : [];
        } catch {
            return [];
        }
    }

    // Хлебные крошки
    const bookBreadcrumb = document.getElementById("bookBreadcrumb");

    if (bookBreadcrumb) {
        bookBreadcrumb.textContent = book.title;
    }

    // Добавляем книгу или изменяем её статус
    function addToLibrary() {
        const library = loadLibrary();
        const existingBook = library.find(item => item.id === bookId);

        if (existingBook) {
            existingBook.status = statusSelect.value;
            message.textContent =
                "Статус книги в библиотеке обновлён!";
        } else {
            library.push({
                id: bookId,
                status: statusSelect.value
            });

            message.textContent =
                "Книга добавлена в твою библиотеку!";
        }

        try {
            localStorage.setItem(storageKey, JSON.stringify(library));
        } catch {
            message.textContent =
                "Не удалось сохранить книгу в браузере.";
        }
    }

    // Показываем текущий статус сохранённой книги
    const savedBook = loadLibrary().find(item => item.id === bookId);

    if (savedBook) {
        statusSelect.value = savedBook.status;
        addButton.textContent = "Сохранить статус";
    }

    addButton.addEventListener("click", addToLibrary);

} else {
    bookNotFound.classList.remove("d-none");
}
